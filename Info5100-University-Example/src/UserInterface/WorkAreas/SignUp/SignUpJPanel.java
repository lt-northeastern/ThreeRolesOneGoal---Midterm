    private void btnCreateAccountActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCreateAccountActionPerformed
        // TODO add your handling code here:
         String name = txtFullName.getText().trim();
        String nuid = txtNUID.getText().trim();
        String username = txtUserName.getText().trim();
        String password = new String(pwEntry.getPassword());
        String confirm = new String(pwConfirm.getPassword());
       

        if (name.isEmpty() || nuid.isEmpty() || username.isEmpty() || password.isEmpty() || confirm.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Please fill in all fields", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (!password.equals(confirm)) {
            JOptionPane.showMessageDialog(null, "The passwords do not match", "Warning", JOptionPane.WARNING_MESSAGE);
            pwEntry.setText("");
            pwConfirm.setText("");
            return;
        }
        try {
            business.signUpStudent(name, nuid, username, password);
        } catch (IllegalArgumentException exception) {
            JOptionPane.showMessageDialog(this, exception.getMessage(),"Error",JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        JOptionPane.showMessageDialog(null, "Student Account Created, you can login with the account now.", "Information", JOptionPane.INFORMATION_MESSAGE);
        txtFullName.setText("");
        txtNUID.setText("");
        txtUserName.setText("");
        pwEntry.setText("");
        pwConfirm.setText("");

        userProcessContainer.remove(this);
        CardLayout layout = (CardLayout) userProcessContainer.getLayout();
        layout.first(userProcessContainer);
    }//GEN-LAST:event_btnCreateAccountActionPerformed


