    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:

            UserAccount ua = selectedAccount();
        if (ua == null) {
            JOptionPane.showMessageDialog(this, "Please select an account in the table first.", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (ua == currentUser) {
            JOptionPane.showMessageDialog(this, "You cannot delete the account you are logged in with.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        if (!confirm("Delete the login account \"" + ua.getUserLoginName() + "\"?\n"
                + "The person's profile is kept; use the Manage screens to delete the profile too.")) {
            return;
        }
        business.getUserAccountDirectory().removeUserAccount(ua);
        refreshTable();
        clearFields();
        JOptionPane.showMessageDialog(this, "The account was deleted.");
    

    }//GEN-LAST:event_btnDeleteActionPerformed

