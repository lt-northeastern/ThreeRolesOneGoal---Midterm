    /**
     * Logs a user in. Warns when a field is blank and shows a "Login failed" message for a
     * wrong username or password. On success it remembers the current user, records the login
     * time, clears the password and opens the Admin, Student or Faculty work area based on the
     * profile type.
     *
     * Christopher Ogden NUID: 003959375 Contributed from Assignment 3 codebase.
     */
    private void LoginButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_LoginButtonActionPerformed
        // TODO add your handling code here:
        //      WorkAreaJPanel ura = new WorkAreaJPanel(workareajpanl);


        String un = UserNameTextField.getText();
        String pw = new String(pwEntry.getPassword());
        if (un.trim().isEmpty() || pw.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter your user name and password.",
                    "Login", JOptionPane.WARNING_MESSAGE);
            return;
        }

        UserAccountDirectory uad = business.getUserAccountDirectory();
        UserAccount useraccount = uad.AuthenticateUser(un, pw);
        
        if (useraccount == null) {
            JOptionPane.showMessageDialog(this, "Invalid user name or password. Please try again.",
                    "Login failed", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        // Christopher Ogden NUID: 003959375 Admin use case: a disabled account cannot log in
        if (!useraccount.isActive()) {
            pwEntry.setText("");
            JOptionPane.showMessageDialog(this, "This account has been disabled. Please contact an administrator.",
                    "Login failed", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        StudentWorkAreaJPanel studentworkareajpanel;
        FacultyWorkAreaJPanel facultyworkarea;
        AdminRoleWorkAreaJPanel adminworkarea;
        String r = useraccount.getRole();
        Profile profile = useraccount.getAssociatedPersonProfile();

        currentUser = useraccount;
        useraccount.recordLogin();
        pwEntry.setText("");

        if (profile instanceof EmployeeProfile) {

            adminworkarea = new AdminRoleWorkAreaJPanel(business, useraccount, CardSequencePanel);
            CardSequencePanel.removeAll();
            CardSequencePanel.add("Admin", adminworkarea);
            ((java.awt.CardLayout) CardSequencePanel.getLayout()).next(CardSequencePanel);

        }

        if (profile instanceof StudentProfile) {

        studentworkareajpanel = new StudentWorkAreaJPanel(business, useraccount, CardSequencePanel);
        CardSequencePanel.removeAll();
        CardSequencePanel.add("student", studentworkareajpanel);
        ((java.awt.CardLayout) CardSequencePanel.getLayout()).next(CardSequencePanel);

        }

        if (profile instanceof FacultyProfile) {
            facultyworkarea = new FacultyWorkAreaJPanel(business, currentUser, CardSequencePanel);
            CardSequencePanel.removeAll();
            CardSequencePanel.add("faculty", facultyworkarea);
            ((java.awt.CardLayout) CardSequencePanel.getLayout()).next(CardSequencePanel);

        }


    }//GEN-LAST:event_LoginButtonActionPerformed

    /**
     * Logs the current user out: clears the login fields, returns to the welcome card and
     * confirms with a message. Warns when nobody is logged in.
     *
     * Christopher Ogden NUID: 003959375 Contributed from Assignment 3 codebase.
     */
    private void btnLogoutLoginButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLogoutLoginButtonActionPerformed
        // TODO add your handling code here:
        if (currentUser == null) {
             JOptionPane.showMessageDialog(this, "You are not logged in.");
             return;
         }
         currentUser = null;
         UserNameTextField.setText("");
         pwEntry.setText("");
         
        CardSequencePanel.removeAll();
        CardSequencePanel.add("welcome", jLabel3);
        java.awt.CardLayout layout = (java.awt.CardLayout) CardSequencePanel.getLayout();
        layout.previous(CardSequencePanel);
    
         JOptionPane.showMessageDialog(this, "You have been logged out.");
    }//GEN-LAST:event_btnLogoutLoginButtonActionPerformed

    /**
     * Opens the Sign-up page to create a new student account. Blocked with a message while
     * someone is logged in.
     *
     * Christopher Ogden NUID: 003959375 Contributed from Assignment 3 codebase.
     */
    private void btnSignupLoginButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSignupLoginButtonActionPerformed
        // TODO add your handling code here:
        if (currentUser != null) {
            JOptionPane.showMessageDialog(this,
                    "You are logged in as \"" + currentUser.getUserLoginName() + "\".\n"
                    + "Please log out first to create a new student account.",
                    "Sign Up", JOptionPane.INFORMATION_MESSAGE);
            return;
        }
        CardSequencePanel.removeAll();
        CardSequencePanel.add("welcome", jLabel3);          // welcome is always the first card
        SignUpJPanel signup = new SignUpJPanel(business, CardSequencePanel);
        CardSequencePanel.add("signup", signup);
        ((java.awt.CardLayout) CardSequencePanel.getLayout()).next(CardSequencePanel);
    }//GEN-LAST:event_btnSignupLoginButtonActionPerformed

